import '@/app/globals.css';
import I18nProvider from '@/i18n/I18nProvider';
import {
  getHtmlLang,
  LANGUAGE_COOKIE_KEY,
  languageFromRequest,
  type Language,
} from '@/i18n/language';
import type { Metadata } from 'next';
import { cookies, headers } from 'next/headers';
import type { JSX, ReactNode } from 'react';

export const metadata: Metadata = {
  title: 'Budget Manager',
  description: 'Generated by Erick',
};

const themeScript = `
(() => {
  const themes = ['latte', 'macchiato'];
  const storedTheme = localStorage.getItem('budget-manager-theme');

  const resolved = window.matchMedia('(prefers-color-scheme: light)').matches ? 'latte' : 'macchiato';
  let selectedTheme = 'macchiato';
  if (storedTheme === 'system') {
    selectedTheme = resolved;
  } else if (themes.includes(storedTheme)) {
    selectedTheme = storedTheme;
  }
  document.documentElement.dataset.theme = selectedTheme;
})();
`;

export default async function RootLayout({
  children,
}: Readonly<{
  children: ReactNode;
}>): Promise<JSX.Element> {
  const cookieStore = await cookies();
  const headerStore = await headers();
  const cookieValue: string | undefined =
    cookieStore.get(LANGUAGE_COOKIE_KEY)?.value;
  const acceptLanguage: string | null = headerStore.get('accept-language');
  const initialLanguage: Language = languageFromRequest(
    cookieValue,
    acceptLanguage
  );
  const htmlLang: 'en' | 'pt-BR' = getHtmlLang(initialLanguage);

  return (
    <html className="h-full" lang={htmlLang} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body
        className="min-h-screen text-[var(--ctp-text)] antialiased transition-colors"
        suppressHydrationWarning
      >
        <I18nProvider initialLanguage={initialLanguage}>
          {children}
        </I18nProvider>
      </body>
    </html>
  );
}
